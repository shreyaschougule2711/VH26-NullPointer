# 3. COMPOSITE PRESSURE & EDF-INSPIRED DECISION ENGINE
# ═══════════════════════════════════════════════════════════════════════


class AdaptiveDecisionEngine:
    """
    Multi-Factor Decision Engine combining:
      - Priority Score (0-100)
      - System Pressure (0-100)
      - Earliest Deadline First (EDF) Score (0-100)
      - Queue Occupancy Score (0-100)
      - Worker Stress Score (0-100)
      - Queue Aging (starvation prevention)
    """

    def __init__(self, max_queue: int = 5000, target_lat: float = 200.0, aging_limit_sec: float = 20.0):
        self.max_queue = max_queue
        self.target_lat = target_lat
        self.aging_limit_sec = aging_limit_sec

    def compute_pressure(self, queue_size: int, worker_util: float, avg_latency: float) -> tuple:
        q = min(1.0, queue_size / max(1, self.max_queue))
        u = min(1.0, max(0.0, worker_util))
        l = min(1.0, avg_latency / max(1, self.target_lat))
        # Formula: P = 0.40 Q + 0.35 U + 0.25 L
        score = round(min(1.0, max(0.0, 0.40 * q + 0.35 * u + 0.25 * l)), 4)

        if score < 0.40:
            level = "LOW"
        elif score < 0.75:
            level = "MEDIUM"
        elif score < 0.95:
            level = "HIGH"
        else:
            level = "CRITICAL"
        return level, score

    def evaluate_event(self, event: Event, pressure_score: float, queue_depth: int,
                       worker_load: float, cur_time: float) -> Dict[str, Any]:
        # 1. Sub-Scores (0 to 100)
        priority_score = event.priority
        pressure_100 = round(pressure_score * 100, 1)
        queue_score = round(min(100.0, (queue_depth / self.max_queue) * 100), 1)
        worker_score = round(worker_load * 100, 1)

        # EDF urgency score: closer to deadline -> higher EDF score
        remaining = max(0.01, event.deadline - cur_time)
        event.remaining_time = remaining
        event.waiting_time = max(0.0, cur_time - event.arrival_time)
        total_sla = EVENT_CATEGORIES.get(event.event_type, {}).get("deadlineSec", 10.0)
        edf_score = round(min(100.0, max(0.0, (1.0 - (remaining / total_sla)) * 100)), 1)

        # 2. Aging Evaluation (Starvation Prevention)
        if event.waiting_time >= self.aging_limit_sec and not event.escalated:
            event.escalated = True
            event.priority = min(100, event.priority + 30)
            return {
                "decision": "PROCESS",
                "reason": f"Priority Escalated (Waited {round(event.waiting_time, 1)}s > 20s)",
                "scores": {"priority": priority_score, "pressure": pressure_100, "edf": 99.0, "queue": queue_score, "worker": worker_score, "final": 95.0},
                "escalated": True,
            }

        # 3. Critical Events: Never drop, never batch
        if event.category == "CRITICAL":
            return {
                "decision": "PROCESS",
                "reason": "Critical Event (Payment/Order/Security SLA Guaranteed)",
                "scores": {"priority": priority_score, "pressure": pressure_100, "edf": edf_score, "queue": queue_score, "worker": worker_score, "final": 98.0},
                "escalated": False,
            }

        # 4. Batch Queue Events (Medium Priority: Inventory, Notifications, Email, Analytics)
        if event.category == "BATCH":
            if pressure_score < 0.35 and queue_depth < 300:
                decision = "PROCESS"
                reason = "Low Pressure Immediate Dispatch"
            else:
                decision = "BATCH"
                reason = "Adaptive Batching (Efficiency Optimization)"
            final_score = round(priority_score * 0.4 + edf_score * 0.3 + (100 - pressure_100) * 0.3, 1)
            return {
                "decision": decision,
                "reason": reason,
                "scores": {"priority": priority_score, "pressure": pressure_100, "edf": edf_score, "queue": queue_score, "worker": worker_score, "final": final_score},
                "escalated": False,
            }

        # 5. Deferred Queue Events (Low Priority: Clickstream, Logs, Metrics, Activity)
        if pressure_score < 0.40 and queue_depth < 200:
            decision = "PROCESS"
            reason = "Idle Capacity Absorbing Low Priority"
        elif pressure_score < 0.75:
            decision = "BATCH"
            reason = "Micro-Batched Telemetry"
        elif pressure_score < 0.95:
            decision = "DEFER"
            reason = "High Pressure Backpressure Relief (Deferred Queue)"
        else:
            decision = "DROP"
            reason = "Emergency Load Shedding (Protecting Critical Ingress)"

        final_score = round(priority_score * 0.3 + edf_score * 0.2 + (100 - pressure_100) * 0.5, 1)
        return {
            "decision": decision,
            "reason": reason,
            "scores": {"priority": priority_score, "pressure": pressure_100, "edf": edf_score, "queue": queue_score, "worker": worker_score, "final": final_score},
            "escalated": False,
        }


