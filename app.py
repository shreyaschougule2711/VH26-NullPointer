    # ────────── Traffic Generation Curves ──────────

    def _calc_target_eps(self, t: float) -> float:
        c = self.config
        pattern = c.pattern.upper()

        if pattern == "SUDDEN_SPIKE":
            if t < c.spikeStartSec:
                return float(c.baseEps)
            elif t < c.spikeStartSec + c.spikeDurationSec:
                return float(c.baseEps * c.spikeMultiplier)
            elif t < c.spikeStartSec + c.spikeDurationSec + c.rampDownSec:
                frac = (t - c.spikeStartSec - c.spikeDurationSec) / max(0.1, c.rampDownSec)
                return c.baseEps * c.spikeMultiplier * (1 - frac) + c.baseEps * frac
            return float(c.baseEps)

        elif pattern == "GRADUAL_RAMP":
            if t < c.spikeStartSec:
                return float(c.baseEps)
            half = c.spikeDurationSec / 2.0
            peak = c.baseEps * c.spikeMultiplier
            if t < c.spikeStartSec + half:
                frac = (t - c.spikeStartSec) / max(0.1, half)
                return c.baseEps + (peak - c.baseEps) * frac
            elif t < c.spikeStartSec + c.spikeDurationSec:
                frac = (t - c.spikeStartSec - half) / max(0.1, half)
                return peak - (peak - c.baseEps) * frac
            return float(c.baseEps)

        elif pattern == "WAVE":
            freq = 0.25
            amp = (c.spikeMultiplier - 1.0) * 0.5
            return float(c.baseEps * (1.0 + amp + amp * math.sin(2 * math.pi * freq * t)))

        elif pattern == "RANDOM_BURST":
            if random.random() < 0.12:
                return float(c.baseEps * c.spikeMultiplier * random.uniform(0.6, 1.0))
            return float(c.baseEps * random.uniform(0.85, 1.15))

        elif pattern == "CONTINUOUS_HIGH_LOAD":
            return float(c.baseEps * c.spikeMultiplier)

        return float(c.baseEps)

    # ────────── Event Generator Factory ──────────

    def _generate_synthetic_event(self, cur_time: float) -> Event:
        # Weighted event distribution
        event_names = list(EVENT_CATEGORIES.keys())
        weights = [
            18, 15, 12, 5,       # Critical: Payment, Order, Auth, Security
            15, 12, 8, 5,        # Batch: Inventory, Notification, Email, Analytics
            5, 4, 3, 3           # Deferred: Clickstream, Log, Metric, UserActivity
        ]
        chosen = random.choices(event_names, weights=weights, k=1)[0]
        meta = EVENT_CATEGORIES[chosen]

        # Deterministic prefix
        prefix = chosen[:3]
        num = random.randint(1000, 9999)
        event_id = f"{prefix}-{num}"
        order_id = f"ORD-{random.randint(100, 999)}"
        user_id = f"USR-{random.randint(10, 99)}"
        amount = round(random.uniform(15.0, 450.0), 2)
        source_id = f"gateway-{random.randint(1, 4):02d}"

        # If duplicate probability triggers, simulate either Rule 1 (Same Event ID) or Rule 2 (Same Payload Hash)
        is_dup_trigger = random.random() < self.config.duplicateProbability
        if is_dup_trigger and self.duplicate_engine.seen_ids:
            if random.random() < 0.5:
                # Rule 1: Reuse an existing Event ID collision
                event_id = random.choice(list(self.duplicate_engine.seen_ids.keys())[-30:])
                payload_str = f"{order_id}_{amount}_{user_id}_{chosen}"
                payload_hash = hashlib.sha256(payload_str.encode("utf-8")).hexdigest()[:16]
            else:
                # Rule 2: Reuse an existing Payload Hash within 30s sliding window
                if self.duplicate_engine.payload_hashes:
                    payload_hash = random.choice(list(self.duplicate_engine.payload_hashes.keys())[-30:])
                else:
                    payload_str = f"{order_id}_{amount}_{user_id}_{chosen}"
                    payload_hash = hashlib.sha256(payload_str.encode("utf-8")).hexdigest()[:16]
        else:
            # Unique SHA256 Payload Hash: OrderID + Amount + User + Type
            payload_str = f"{order_id}_{amount}_{user_id}_{chosen}"
            payload_hash = hashlib.sha256(payload_str.encode("utf-8")).hexdigest()[:16]

        deadline = cur_time + meta["deadlineSec"]

        return Event(
            event_id=event_id,
            order_id=order_id,
            user_id=user_id,
            amount=amount,
            event_type=chosen,
            category=meta["category"],
            source_id=source_id,
            timestamp=cur_time,
            payload_hash=payload_hash,
            priority=meta["priority"],
            deadline=deadline,
            arrival_time=cur_time,
            retry_count=0,
            status="ARRIVED",
        )

    # ────────── Main Processing Loop ──────────

    async def _loop(self):
        dt = self.TICK_DT
        try:
            while self.running:
                cur_time = time.time() - self.start_time
                target_eps = self._calc_target_eps(cur_time)
                self.cur_eps = target_eps
                self.peak_eps = max(self.peak_eps, target_eps)

                # 1. Ingress Generation
                n_events = int(target_eps * dt + random.uniform(0, 0.9))
                for _ in range(n_events):
                    evt = self._generate_synthetic_event(cur_time)
                    self.total_generated += 1
                    self._sec_gen += 1

                    # ── FEATURE 1: PRE-INGRESS DUPLICATE DETECTION ──
                    dup_record = self.duplicate_engine.check_duplicate(evt, cur_time)
                    if dup_record:
                        # Event quarantined as duplicate!
                        continue

                    # Place into Raw Ingress Queue
                    self.q_raw.append(evt)

                # 2. Dynamic Worker Scaling based on Pressure
                current_total_q = len(self.q_raw) + len(self.q_critical) + len(self.q_batch) + len(self.q_deferred) + len(self.q_retry)
                scaling_mode = self.worker_fleet.scale_fleet(self.cur_pressure_score)

                # 3. Dynamic Adaptive Batch Sizing (Feature 1)
                # Queue Size Thresholds:
                # If Queue Size < 500   -> Batch Size = 10
                # If Queue Size > 1000  -> Batch Size = 25
                # If Queue Size > 3000  -> Batch Size = 50
                # If Queue Size > 5000  -> Batch Size = 100
                # If Queue Size > 10000 -> Batch Size = 200
                if current_total_q < 500:
                    base_bs = 10
                elif current_total_q < 1000:
                    base_bs = 15
                elif current_total_q < 3000:
                    base_bs = 25
                elif current_total_q < 5000:
                    base_bs = 50
                elif current_total_q < 10000:
                    base_bs = 100
                else:
                    base_bs = 200

                # Continuously adapt based on pressure
                if self.cur_pressure_score > 0.85:
                    base_bs = max(base_bs, 100)
                elif self.cur_pressure_score > 0.60:
                    base_bs = max(base_bs, 50)
                elif self.cur_pressure_score > 0.40:
                    base_bs = max(base_bs, 25)

                self.adaptive_batch_size = base_bs

                # 4. Adaptive Decision Routing & Queue Dispatch
                # Capacity: 15,000 events/sec classification rate
                budget_classify = int(15000 * dt)
                to_classify = min(len(self.q_raw), budget_classify)

                for _ in range(to_classify):
                    evt = self.q_raw.popleft()
                    eval_result = self.decision_engine.evaluate_event(
                        evt, self.cur_pressure_score, current_total_q,
                        sum(self.worker_fleet.utilization.values()) / 4.0, cur_time
                    )
                    outcome = eval_result["decision"]
                    reason = eval_result["reason"]
                    scores = eval_result["scores"]

                    if eval_result.get("escalated"):
                        self.priority_escalations += 1

                    if outcome == "PROCESS":
                        evt.status = "QUEUED_CRITICAL"
                        self.q_critical.append(evt)
                    elif outcome == "BATCH":
                        evt.status = "QUEUED_BATCH"
                        self.q_batch.append(evt)
                    elif outcome == "DEFER":
                        evt.status = "QUEUED_DEFERRED"
                        self.q_deferred.append(evt)
                    elif outcome == "DROP":
                        evt.status = "DROPPED"
                        self.total_dropped += 1

                    self.dec_counts[outcome] = self.dec_counts.get(outcome, 0) + 1

                    # Keep decision audit trail
                    self.recent_decisions.appendleft({
                        "time": datetime.now(timezone.utc).strftime("%H:%M:%S.%f")[:-3],
                        "eventId": evt.event_id,
                        "eventType": evt.event_type,
                        "category": evt.category,
                        "priority": evt.priority,
                        "queue": current_total_q,
                        "pressure": round(self.cur_pressure_score, 2),
                        "decision": outcome,
                        "reason": reason,
                        "latency": round(self.cur_latency, 1),
                        "scores": scores,
                    })

                # 5. Check Queue Aging in Deferred Queue
                # If waiting time > 20 sec, escalate priority
                aging_check_count = min(30, len(self.q_deferred))
                for _ in range(aging_check_count):
                    if self.q_deferred:
                        def_evt = self.q_deferred[0]
                        if (cur_time - def_evt.arrival_time) >= 20.0:
                            def_evt = self.q_deferred.popleft()
                            def_evt.escalated = True
                            def_evt.priority = 95
                            def_evt.category = "CRITICAL"
                            self.q_critical.append(def_evt)
                            self.priority_escalations += 1
                            self.recent_decisions.appendleft({
                                "time": datetime.now(timezone.utc).strftime("%H:%M:%S.%f")[:-3],
                                "eventId": def_evt.event_id,
                                "eventType": def_evt.event_type,
                                "category": "CRITICAL",
                                "priority": def_evt.priority,
                                "queue": current_total_q,
                                "pressure": round(self.cur_pressure_score, 2),
                                "decision": "PROCESS",
                                "reason": "Priority Escalated (Waited > 20s in Deferred)",
                                "latency": round(self.cur_latency, 1),
                                "scores": {"priority": 95, "pressure": round(self.cur_pressure_score * 100, 1), "edf": 99.0, "queue": 80.0, "worker": 80.0, "final": 95.0},
                            })

                # 6. Worker Execution Pools
                # Capacities based on active worker scaling counts
                crit_workers = self.worker_fleet.active_counts["critical"]
                batch_workers = self.worker_fleet.active_counts["batch"]
                def_workers = self.worker_fleet.active_counts["deferred"]
                retry_workers = self.worker_fleet.active_counts["retry"]

                # A. Critical Pool: 1,500 EPS per worker thread
                cap_crit = int(crit_workers * 1500 * dt)
                crit_to_proc = min(len(self.q_critical), cap_crit)
                crit_processed = 0
                for _ in range(crit_to_proc):
                    if not self.q_critical:
                        break
                    evt = self.q_critical.popleft()
                    if random.random() < self.config.failureProbability:
                        self._handle_failure(evt, cur_time)
                    else:
                        self.duplicate_engine.mark_completed(evt.event_id)
                        crit_processed += 1
                        self.total_processed += 1
                        self._sec_proc += 1
                self.worker_fleet.process_workload("critical", crit_processed, f"CRITICAL ({crit_to_proc} active)")
                self.worker_fleet.utilization["critical"] = min(1.0, crit_to_proc / max(1, cap_crit)) if cap_crit > 0 else 0.0

                # B. Batch Pool: Processed in dynamic batches (Feature 1)
                batch_size = self.adaptive_batch_size
                cap_batch_items = int(batch_workers * 1000 * dt)
                batch_to_proc = min(len(self.q_batch), cap_batch_items)
                batch_processed = 0
                batch_calls_this_tick = 0

                while batch_processed < batch_to_proc and self.q_batch:
                    chunk = min(batch_size, len(self.q_batch), batch_to_proc - batch_processed)
                    if chunk <= 0:
                        break
                    batch_calls_this_tick += 1
                    self.total_batch_calls += 1
                    for _ in range(chunk):
                        if not self.q_batch:
                            break
                        evt = self.q_batch.popleft()
                        batch_processed += 1
                        if random.random() < self.config.failureProbability:
                            self._handle_failure(evt, cur_time)
                        else:
                            self.duplicate_engine.mark_completed(evt.event_id)
                            self.total_processed += 1
                            self.total_batched += 1
                            self._sec_proc += 1

                self.worker_fleet.process_workload("batch", batch_processed, f"BATCH ({batch_calls_this_tick} calls, x{batch_size})")
                self.worker_fleet.utilization["batch"] = min(1.0, batch_to_proc / max(1, cap_batch_items)) if cap_batch_items > 0 else 0.0

                # C. Deferred Pool: 400 EPS per worker
                cap_def = int(def_workers * 400 * dt)
                def_to_proc = min(len(self.q_deferred), cap_def)
                def_processed = 0
                for _ in range(def_to_proc):
                    if not self.q_deferred:
                        break
                    evt = self.q_deferred.popleft()
                    if random.random() < self.config.failureProbability:
                        self._handle_failure(evt, cur_time)
                    else:
                        self.duplicate_engine.mark_completed(evt.event_id)
                        def_processed += 1
                        self.total_processed += 1
                        self.total_deferred_proc += 1
                        self._sec_proc += 1
                self.worker_fleet.process_workload("deferred", def_processed, f"DEFERRED ({def_to_proc} active)")
                self.worker_fleet.utilization["deferred"] = min(1.0, def_to_proc / max(1, cap_def)) if cap_def > 0 else 0.0

                # D. Retry Pool: Exponential backoff re-execution
                cap_retry = int(retry_workers * 500 * dt)
                retry_to_proc = min(len(self.q_retry), cap_retry)
                retry_processed = 0
                for _ in range(retry_to_proc):
                    if not self.q_retry:
                        break
                    evt = self.q_retry.popleft()
                    if random.random() < (self.config.failureProbability * 0.5):
                        self._handle_failure(evt, cur_time)
                    else:
                        self.duplicate_engine.mark_completed(evt.event_id)
                        retry_processed += 1
                        self.total_processed += 1
                        self._sec_proc += 1
                self.worker_fleet.process_workload("retry", retry_processed, f"RETRY ({retry_to_proc} active)")
                self.worker_fleet.utilization["retry"] = min(1.0, retry_to_proc / max(1, cap_retry)) if cap_retry > 0 else 0.0

                # 7. Dynamic Latency & System Pressure Calculation
                total_q = len(self.q_raw) + len(self.q_critical) + len(self.q_batch) + len(self.q_deferred) + len(self.q_retry)
                avg_worker_util = sum(self.worker_fleet.utilization.values()) / 4.0

                # Physics-based latency model
                q_factor = min(1.0, total_q / 5000)
                u_factor = avg_worker_util
                self.cur_latency = round(min(280.0, 15.0 * (1.0 + q_factor * 5.0 + (u_factor ** 2) * 8.0)), 1)
                self.peak_latency = max(self.peak_latency, self.cur_latency)

                # Pressure Recalculation
                self.cur_pressure_level, self.cur_pressure_score = self.decision_engine.compute_pressure(
                    total_q, avg_worker_util, self.cur_latency
                )

                # 8. Actual EPS & Queue Growth Rate Calculation (Every 1.0s)
                if cur_time - self._last_sec >= 1.0:
                    self.actual_eps = self._sec_proc
                    self.queue_growth_rate = round((total_q - self._last_queue_size), 1)
                    self._last_queue_size = total_q
                    self._sec_gen = 0
                    self._sec_proc = 0
                    self._last_sec = cur_time

                # 9. FEATURE 3: Real-time Normalized Infrastructure Cost Calculation (Cost Units)
                naive_events_this_tick = crit_to_proc + batch_to_proc + def_to_proc + retry_to_proc + len(self.duplicate_engine.duplicate_queue)
                adaptive_ops_this_tick = crit_processed + batch_calls_this_tick + def_processed + retry_processed

                self.cost_estimator.tick(
                    dt=dt,
                    naive_events_tick=naive_events_this_tick,
                    adaptive_ops_tick=adaptive_ops_this_tick,
                    naive_q_size=total_q * 2,
                    adaptive_q_size=total_q,
                    pressure_score=self.cur_pressure_score,
                    current_workers=sum(self.worker_fleet.active_counts.values()),
                )

                # 10. Time Series Serialization
                self._tick += 1
                if self._tick % self.CHART_TICKS == 0:
                    self.ts_t.append(round(cur_time, 1))
                    self.ts_throughput.append(round(self.actual_eps))
                    self.ts_latency.append(round(self.cur_latency, 1))
                    self.ts_pressure.append(round(self.cur_pressure_score, 3))
                    self.ts_q_crit.append(len(self.q_critical))
                    self.ts_q_batch.append(len(self.q_batch))
                    self.ts_q_def.append(len(self.q_deferred))
                    self.ts_cost_naive.append(self.cost_estimator.naive_total)
                    self.ts_cost_adaptive.append(self.cost_estimator.adaptive_total)

                    if len(self.ts_t) > self.MAX_CHART_PTS:
                        for arr in (self.ts_t, self.ts_throughput, self.ts_latency, self.ts_pressure,
                                    self.ts_q_crit, self.ts_q_batch, self.ts_q_def,
                                    self.ts_cost_naive, self.ts_cost_adaptive):
                            arr.pop(0)

                await asyncio.sleep(dt)

        except asyncio.CancelledError:
            pass
        finally:
            self.running = False

    def _handle_failure(self, event: Event, cur_time: float):
        self.total_failures += 1
        event.retry_count += 1
        max_retries = EVENT_CATEGORIES.get(event.event_type, {}).get("maxRetries", 2)

        if event.category == "CRITICAL" or event.retry_count <= max_retries:
            event.status = "RETRYING"
            self.q_retry.append(event)
            self.total_retried += 1
            self.dec_counts["RETRY"] = self.dec_counts.get("RETRY", 0) + 1
        else:
            # Maximum retries exceeded -> Dead Letter Queue
            event.status = "DLQ_QUARANTINED"
            event.failure_reason = f"Max retries ({max_retries}) exceeded"
            self.dlq.append({
                "eventId": event.event_id,
                "eventType": event.event_type,
                "category": event.category,
                "priority": event.priority,
                "retryCount": event.retry_count,
                "failureReason": event.failure_reason,
                "timestamp": datetime.now(timezone.utc).strftime("%H:%M:%S.%f")[:-3],
                "arrivalTime": round(event.arrival_time, 1),
            })

