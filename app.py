class WorkerFleetManager:
    """
    Dynamic Worker Fleet with Adaptive Pressure-Based Scaling and Live Thread Health.
    Scaling Levels:
      - Normal (<40%):   Crit=2, Batch=1, Def=1 (Total: 4)
      - Medium (40-80%): Crit=4, Batch=2, Def=2 (Total: 8)
      - High (80-95%):   Crit=6, Batch=4, Def=2 (Total: 12)
      - Emergency (>95%):Crit=8, Batch=6, Def=2 (Total: 16)
    """

    def __init__(self):
        self.scaling_level = "NORMAL"
        self.active_counts = {"critical": 2, "batch": 1, "deferred": 1, "retry": 1}
        self.utilization = {"critical": 0.0, "batch": 0.0, "deferred": 0.0, "retry": 0.0}
        self.processed = {"critical": 0, "batch": 0, "deferred": 0, "retry": 0}
        self.avg_proc_ms = {"critical": 18.0, "batch": 42.0, "deferred": 95.0, "retry": 30.0}
        self.health = {"critical": 100, "batch": 100, "deferred": 100, "retry": 100}
        self.current_event = {
            "critical": "PAYMENT (#ORD-1042)",
            "batch": "INVENTORY (Batch x25)",
            "deferred": "CLICKSTREAM (Stream)",
            "retry": "IDLE",
        }

    def scale_fleet(self, pressure_score: float) -> str:
        if pressure_score < 0.40:
            self.scaling_level = "NORMAL"
            self.active_counts = {"critical": 2, "batch": 1, "deferred": 1, "retry": 1}
        elif pressure_score < 0.80:
            self.scaling_level = "ELEVATED"
            self.active_counts = {"critical": 4, "batch": 2, "deferred": 2, "retry": 1}
        elif pressure_score < 0.95:
            self.scaling_level = "HIGH_LOAD"
            self.active_counts = {"critical": 6, "batch": 4, "deferred": 2, "retry": 2}
        else:
            self.scaling_level = "EMERGENCY_MODE"
            self.active_counts = {"critical": 8, "batch": 6, "deferred": 2, "retry": 2}
        return self.scaling_level

    def process_workload(self, pool_type: str, count: int, current_event_name: str = ""):
        self.processed[pool_type] = self.processed.get(pool_type, 0) + count
        if current_event_name:
            self.current_event[pool_type] = current_event_name

    def get_status(self) -> Dict[str, Any]:
        return {
            "scalingLevel": self.scaling_level,
            "emergencyMode": self.scaling_level == "EMERGENCY_MODE",
            "totalWorkers": sum(self.active_counts.values()),
            "activeCounts": dict(self.active_counts),
            "utilization": {k: round(v * 100, 1) for k, v in self.utilization.items()},
            "processed": dict(self.processed),
            "avgProcessingMs": dict(self.avg_proc_ms),
            "currentEvent": dict(self.current_event),
            "health": dict(self.health),
        }


