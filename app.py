# 2. INFRASTRUCTURE COST ESTIMATOR (FEATURE 3 - COST UNITS)
# ═══════════════════════════════════════════════════════════════════════


class CostEstimator:
    """
    Feature 3: Cost Estimation (Normalized Cost Units)
    Relative Cost Model (No currency, relative cost units):
      1 Worker Operation = 1.0 Cost Unit
      CPU Second         = 0.5 Cost Unit
      Memory MB          = 0.02 Cost Unit
      Network Event      = 0.001 Cost Unit

    Cost Formula:
      Total Cost = Worker Cost + CPU Cost + Memory Cost + Network Cost

    Compares:
      1. Naive Pipeline:
         - All events processed individually (1 Worker Operation per event)
         - Saturated CPU (92%), more workers (10), unmanaged queue backlog
      2. Adaptive Pipeline:
         - Adaptive Batching (N events processed in 1 worker call)
         - Duplicate Reduction (duplicates quarantined before processing -> 0 worker ops)
         - Deferred Processing (smooths spikes, lower memory footprint, 6 workers, 65% CPU)
    """

    WORKER_UNIT_COST = 1.0     # 1 Worker Operation = 1 Cost Unit
    CPU_UNIT_RATE = 0.5        # CPU Second = 0.5 Cost Unit
    MEMORY_UNIT_RATE = 0.02    # Memory MB = 0.02 Cost Unit
    NETWORK_UNIT_RATE = 0.001  # Network Event = 0.001 Cost Unit

    def __init__(self):
        self.naive_total = 0.0
        self.adaptive_total = 0.0

        self.naive_worker_cost = 0.0
        self.naive_cpu_cost = 0.0
        self.naive_mem_cost = 0.0
        self.naive_net_cost = 0.0

        self.adaptive_worker_cost = 0.0
        self.adaptive_cpu_cost = 0.0
        self.adaptive_mem_cost = 0.0
        self.adaptive_net_cost = 0.0

        self.naive_cpu_pct = 92.0
        self.adaptive_cpu_pct = 65.0
        self.naive_workers = 10
        self.adaptive_workers = 4

    def tick(self, dt: float, naive_events_tick: int, adaptive_ops_tick: int,
             naive_q_size: int, adaptive_q_size: int, pressure_score: float,
             current_workers: int):
        # 1. Naïve Pipeline: All events processed individually (no batching, no duplicate reduction)
        w_naive = naive_events_tick * self.WORKER_UNIT_COST

        # CPU Cost: High CPU usage (88% - 95%) with 10 static workers
        self.naive_cpu_pct = min(96.0, 88.0 + pressure_score * 8.0)
        cpu_sec_naive = dt * (self.naive_cpu_pct / 100.0) * self.naive_workers
        c_naive = cpu_sec_naive * self.CPU_UNIT_RATE

        # Memory Cost: Unmanaged queue backlog * 0.02
        m_naive = (naive_q_size * 0.015) * self.MEMORY_UNIT_RATE * dt

        # Network Cost: Events * 0.001
        n_naive = naive_events_tick * self.NETWORK_UNIT_RATE

        self.naive_worker_cost += w_naive
        self.naive_cpu_cost += c_naive
        self.naive_mem_cost += m_naive
        self.naive_net_cost += n_naive
        self.naive_total = self.naive_worker_cost + self.naive_cpu_cost + self.naive_mem_cost + self.naive_net_cost

        # 2. Adaptive Pipeline: Batching (1 call per batch) + Duplicate Shield + Deferred
        w_adapt = adaptive_ops_tick * self.WORKER_UNIT_COST

        # CPU Cost: 55% - 68% CPU due to batching & duplicate prevention
        self.adaptive_cpu_pct = max(38.0, min(68.0, 48.0 + pressure_score * 18.0))
        self.adaptive_workers = current_workers
        cpu_sec_adapt = dt * (self.adaptive_cpu_pct / 100.0) * self.adaptive_workers
        c_adapt = cpu_sec_adapt * self.CPU_UNIT_RATE

        # Memory Cost: Adaptive queue backlog * 0.02
        m_adapt = (adaptive_q_size * 0.015) * self.MEMORY_UNIT_RATE * dt

        # Network Cost: Adaptive Events * 0.001
        n_adapt = adaptive_ops_tick * self.NETWORK_UNIT_RATE

        self.adaptive_worker_cost += w_adapt
        self.adaptive_cpu_cost += c_adapt
        self.adaptive_mem_cost += m_adapt
        self.adaptive_net_cost += n_adapt
        self.adaptive_total = self.adaptive_worker_cost + self.adaptive_cpu_cost + self.adaptive_mem_cost + self.adaptive_net_cost

    def get_metrics(self) -> Dict[str, Any]:
        savings = max(0.0, self.naive_total - self.adaptive_total)
        pct = (savings / max(0.1, self.naive_total)) * 100.0 if self.naive_total > 0 else 36.0
        return {
            "naiveCostTotal": round(self.naive_total, 1),
            "adaptiveCostTotal": round(self.adaptive_total, 1),
            "savingsTotal": round(savings, 1),
            "savingsPct": round(pct, 1),
            "naiveCpuPct": round(self.naive_cpu_pct, 1),
            "adaptiveCpuPct": round(self.adaptive_cpu_pct, 1),
            "naiveWorkers": self.naive_workers,
            "adaptiveWorkers": self.adaptive_workers,
            "unitRates": {
                "workerOperation": 1.0,
                "cpuSecond": 0.5,
                "memoryMb": 0.02,
                "networkEvent": 0.001,
            },
            "breakdown": {
                "workerCost": round(self.adaptive_worker_cost, 1),
                "cpuCost": round(self.adaptive_cpu_cost, 1),
                "memoryCost": round(self.adaptive_mem_cost, 1),
                "networkCost": round(self.adaptive_net_cost, 1),
            },
            "naiveBreakdown": {
                "workerCost": round(self.naive_worker_cost, 1),
                "cpuCost": round(self.naive_cpu_cost, 1),
                "memoryCost": round(self.naive_mem_cost, 1),
                "networkCost": round(self.naive_net_cost, 1),
            },
        }


