# 1. DUPLICATE DETECTION ENGINE (FEATURE 2)
# ═══════════════════════════════════════════════════════════════════════


class DuplicateEngine:
    """
    Feature 2: Duplicate Event Reduction
    Pre-Queue Detection before Adaptive Decision Engine:
      - Cache recent event IDs & SHA-256 payload hashes with 30s sliding window.
      - Rule 1: Same Event ID Collision -> Action: IGNORED
      - Rule 2: Same Payload Hash (OrderID + Amount + User + Type) within 30s -> Action: IGNORED
      - Rule 3: Completed event resubmitted as Retry -> Action: DROPPED
    """

    def __init__(self, window_sec: float = 30.0):
        self.window_sec = window_sec
        self.seen_ids: Dict[str, float] = {}       # event_id -> timestamp
        self.payload_hashes: Dict[str, float] = {} # payload_hash -> timestamp
        self.completed_ids: Set[str] = set()
        self.duplicate_queue: deque = deque(maxlen=200)
        self.duplicate_logs: deque = deque(maxlen=100)
        self.duplicate_timeline: deque = deque(maxlen=30)
        self.total_duplicates = 0
        self.rule_breakdown = {
            "SAME_EVENT_ID": 0,
            "PAYLOAD_HASH_30S_WINDOW": 0,
            "RETRY_COMPLETED_EVENT": 0,
        }

    def check_duplicate(self, event: Event, current_time: float) -> Optional[Dict[str, Any]]:
        # Cleanup expired cache
        if random.random() < 0.02:
            cutoff = current_time - (self.window_sec * 2)
            self.seen_ids = {k: v for k, v in self.seen_ids.items() if v > cutoff}
            self.payload_hashes = {k: v for k, v in self.payload_hashes.items() if v > cutoff}

        # Rule 1: Same Event ID Collision
        if event.event_id in self.seen_ids:
            reason = "SAME_EVENT_ID"
            action = "IGNORED"
            return self._record_dup(event, reason, action, current_time, self.seen_ids[event.event_id])

        # Rule 3: Retry for event that already completed
        if event.retry_count > 0 and event.event_id in self.completed_ids:
            reason = "RETRY_COMPLETED_EVENT"
            action = "DROPPED"
            return self._record_dup(event, reason, action, current_time, current_time - 1.0)

        # Rule 2: Same Payload Hash within 30-second sliding window
        # Payload Hash = SHA256(OrderID + Amount + User + Type)
        if event.payload_hash in self.payload_hashes:
            orig_time = self.payload_hashes[event.payload_hash]
            if (current_time - orig_time) <= self.window_sec:
                reason = "PAYLOAD_HASH_30S_WINDOW"
                action = "IGNORED"
                return self._record_dup(event, reason, action, current_time, orig_time)

        # Unique Event: Cache ID and Payload Hash
        self.seen_ids[event.event_id] = current_time
        self.payload_hashes[event.payload_hash] = current_time
        return None

    def mark_completed(self, event_id: str):
        self.completed_ids.add(event_id)
        if len(self.completed_ids) > 10000:
            self.completed_ids.pop()

    def _record_dup(self, event: Event, reason: str, action: str, cur_time: float, orig_time: float) -> Dict[str, Any]:
        self.total_duplicates += 1
        self.rule_breakdown[reason] = self.rule_breakdown.get(reason, 0) + 1
        event.status = "DUPLICATE_QUARANTINED"
        event.failure_reason = f"Duplicate detected ({reason})"

        dup_record = {
            "eventId": event.event_id,
            "orderId": event.order_id,
            "originalId": event.event_id if reason != "PAYLOAD_HASH_30S_WINDOW" else f"ORIG-{event.order_id}",
            "eventType": event.event_type,
            "sourceId": event.source_id,
            "payloadHash": event.payload_hash[:8] + "...",
            "timestamp": datetime.now(timezone.utc).strftime("%H:%M:%S.%f")[:-3],
            "originalTimestamp": datetime.fromtimestamp(orig_time, tz=timezone.utc).strftime("%H:%M:%S.%f")[:-3] if orig_time > 0 else "--",
            "reason": reason,
            "action": action,
            "cpuSaved": 0.85,
        }
        self.duplicate_queue.append(event)
        self.duplicate_logs.appendleft(dup_record)
        self.duplicate_timeline.appendleft(dup_record)
        return dup_record

    def clear(self):
        self.duplicate_queue.clear()
        self.duplicate_logs.clear()
        self.duplicate_timeline.clear()


